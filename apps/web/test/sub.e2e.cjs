/* subscriptions on a phone: owner warned, admin extends (cash), customer visibility */
const { chromium } = require("/opt/npm-tools/node_modules/playwright");
const path = require("path"), fs = require("fs");
const URL = "file://" + path.resolve(__dirname, "../dist/index.html");
const S = path.resolve(__dirname, "../shots"); fs.mkdirSync(S, { recursive: true });
const errs = [];
(async () => {
  const b = await chromium.launch();
  const c = await b.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 2 });
  const p = await c.newPage(); p.on("pageerror", e => errs.push(e.message));
  const wait = (ms) => p.waitForTimeout(ms || 500);
  const quiet = () => p.evaluate(() => { if (window.SF) { SF.alarmCheck = function () {}; const a = document.querySelector(".alarm"); if (a) a.remove(); } });
  const toast = () => p.evaluate(() => document.querySelector("#toasts").innerText.trim());
  const shot = async (n, full) => { await wait(400); await p.screenshot({ path: S + "/" + n + ".png", fullPage: !!full }); };
  const login = async (phone) => { await p.evaluate(() => window.SF && SF.state.user && SF.actions.logout()); await wait(300); await p.evaluate(() => location.hash = "/login"); await wait(600);
    await p.click(`[data-act=demologin][data-phone="${phone}"]`); await wait(800); await quiet(); };
  await p.goto(URL + "#/"); await p.evaluate(() => { localStorage.clear(); localStorage.setItem("somon.lang", '"tg"'); }); await p.reload(); await wait(800);
  await login("900000101"); await p.evaluate(() => location.hash = "/rest"); await wait(800); await quiet();
  console.log("owner warning:", await p.evaluate(() => (document.querySelector(".subwarn") || {}).innerText));
  await p.evaluate(() => { const t = document.getElementById("toasts"); t.innerHTML = ""; }); await shot("s-owner");
  await login("900000001"); await p.evaluate(() => location.hash = "/admin"); await wait(800);
  console.log("admin alert:", await p.evaluate(() => (document.querySelector(".pcontent .alert") || {}).innerText));
  await p.evaluate(() => location.hash = "/admin/restaurants"); await wait(900);
  console.log("due list:", await p.evaluate(() => (document.querySelector(".subdue") || {}).innerText.replace(/\s+/g, " ")));
  await p.evaluate(() => { document.getElementById("toasts").innerHTML = ""; }); await shot("s-admin-list");
  await p.click(".subdue [data-act=asub]"); await wait(800);
  await p.click('[data-act=asubm][data-v="12"]'); await wait(300);
  console.log("amount for 1 year:", await p.inputValue("#subamt"), "|", await p.evaluate(() => document.getElementById("subnew").innerText));
  await p.fill("#subamt", "3000"); await p.fill("form[data-form=asub] [name=note]", "Нақд, аз Карим");
  await shot("s-admin-modal");
  await p.click("form[data-form=asub] button.primary"); await wait(800); console.log("saved:", await toast());
  console.log("due after:", await p.evaluate(() => !!document.querySelector(".subdue")));
  await p.evaluate(() => location.hash = "/admin/settings"); await wait(800);
  console.log("settings has sub form:", await p.evaluate(() => !!document.querySelector("[data-form=asubset]")));
  await login("900000101"); await p.evaluate(() => location.hash = "/rest/settings"); await wait(900);
  console.log("owner warning after pay:", await p.evaluate(() => !!document.querySelector(".subwarn")), "| notes:", await p.evaluate(() => (SF.state.notes || []).map(n => n.key).join(",")));
  await p.evaluate(() => { const h = [...document.querySelectorAll(".card h3")].find(x => /Обуна/.test(x.innerText)); h.scrollIntoView(); }); await shot("s-owner-settings");
  console.log(errs.length ? "PAGE ERRORS: " + errs.join(" | ") : "NO PAGE ERRORS");
  await b.close();
})();
