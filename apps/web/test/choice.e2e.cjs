/* incoming order on the restaurant phone: choose "we deliver" or "Тезкор courier" */
const { chromium } = require("/opt/npm-tools/node_modules/playwright");
const path = require("path"), fs = require("fs");
const URL = "file://" + path.resolve(__dirname, "../dist/index.html");
const S = path.resolve(__dirname, "../shots"); fs.mkdirSync(S, { recursive: true });
const errs = [];
(async () => {
  const b = await chromium.launch();
  const c = await b.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 2 });
  const p = await c.newPage(); p.on("pageerror", e => errs.push(e.message));
  const wait = (ms) => p.waitForTimeout(ms || 500);
  const go = async (h) => { await p.evaluate((h) => location.hash = h, h); await wait(800); };
  const login = async (phone) => { await p.evaluate(() => window.SF && SF.state.user && SF.actions.logout()); await wait(300); await go("/login"); await p.click(`[data-act=demologin][data-phone="${phone}"]`); await wait(900); };
  const api = (m, u, body) => p.evaluate(([m, u, body]) => SF.api[m](u, body).then(x => x, e => ({ err: e.code || String(e) })), [m, u, body]);
  const toast = () => p.evaluate(() => document.querySelector("#toasts").innerText.trim().split("\n").pop());
  await p.goto(URL + "#/"); await p.evaluate(() => { localStorage.clear(); localStorage.setItem("somon.lang", '"tg"'); }); await p.reload(); await wait(800);
  await login("900000001"); await api("patch", "/admin/restaurants/r1", { delivery: "own" });
  await login("900000301");
  const addr = { text: "кӯчаи Ленин 5", lat: 37.268, lng: 68.145 };
  const o1 = await api("post", "/orders", { restaurantId: "r1", items: [{ productId: "r1p1", qty: 2 }], address: addr, paymentMethod: "cash" });
  await login("900000101"); await go("/rest/orders");
  await p.waitForSelector(".incall .dlch", { timeout: 15000 }); await wait(600);
  await p.evaluate(() => { document.getElementById("toasts").innerHTML = ""; }); await p.screenshot({ path: S + "/ch-call.png" });
  await p.click('.incall [data-act=indeliv][data-v="platform"]'); await wait(300);
  await p.click(".incall [data-act=inaccept]"); await wait(900);
  const x1 = await api("get", "/orders/" + o1.id); console.log("call card choice → delivery:", x1.delivery, "|", await toast());
  await p.evaluate(() => { SF.alarmCheck = function () {}; document.querySelectorAll("#alarm").forEach(a => { a.hidden = true; a.innerHTML = ""; }); });
  await login("900000301"); const o2 = await api("post", "/orders", { restaurantId: "r1", items: [{ productId: "r1p2", qty: 1 }], address: addr, paymentMethod: "cash" });
  await login("900000101"); await p.evaluate(() => { SF.alarmCheck = function () {}; }); await go("/rest/orders"); await p.evaluate(() => { document.querySelectorAll("#alarm").forEach(a => { a.hidden = true; a.innerHTML = ""; }); });
  await p.evaluate((id) => document.querySelector(`[data-act=accept][data-id="${id}"]`).closest(".ticket").scrollIntoView({ block: "center" }), o2.id);
  await p.evaluate(() => { document.getElementById("toasts").innerHTML = ""; }); await p.screenshot({ path: S + "/ch-ticket.png" });
  await p.click(`[data-act=accept][data-id="${o2.id}"]`); await wait(800);
  console.log("ticket default → delivery:", (await api("get", "/orders/" + o2.id)).delivery);
  await p.evaluate((id) => document.querySelector(`[data-act=handoff][data-id="${id}"]`).closest(".ticket").scrollIntoView({ block: "center" }), o2.id);
  await p.evaluate(() => { document.getElementById("toasts").innerHTML = ""; }); await p.screenshot({ path: S + "/ch-cooking.png" });
  await p.click(`[data-act=handoff][data-id="${o2.id}"]`); await wait(800); console.log("handoff:", await toast(), "→", (await api("get", "/orders/" + o2.id)).delivery);
  console.log(errs.length ? "PAGE ERRORS: " + errs.join(" | ") : "NO PAGE ERRORS");
  await b.close();
})();
